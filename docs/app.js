/* Thesis Builder: static UI for GitHub Pages.
 *
 * Reads data/index.json and data/themes/<slug>.json, which are written by the
 * scheduled Claude routine (routines/weekly-theses.md), by
 * `thesis --publish-dir docs/data`, or by scripts/export_demo_data.py.
 * Vanilla JS, no build step. Mermaid and marked come from a CDN.
 */
(function () {
  "use strict";

  var LAYERS = [
    ["raw_inputs", "Raw inputs"],
    ["enabling", "Enabling layers"],
    ["integrators", "Integrators"],
    ["applications", "Applications"],
  ];
  var LAYER_LABEL = {};
  LAYERS.forEach(function (l) { LAYER_LABEL[l[0]] = l[1]; });
  var ANGLE_LABEL = {
    bottleneck_vs_commodity: "Bottleneck or commodity",
    substitution_risk: "Substitution risk",
    priced_in: "Priced in",
  };
  var STANCE_LABEL = { held: "Held", partial: "Partly conceded", conceded: "Conceded" };
  var GEN_LABEL = {
    "claude-routine": "Generated by the scheduled Claude routine (no API calls)",
    "litellm-pipeline": "Generated by the LiteLLM pipeline",
    demo: "Generated by the offline demo pipeline",
  };
  var DIMENSIONS = ["coverage", "specificity", "novelty", "actionability"];

  var state = { index: null, current: null, view: "tree", cache: {} };
  var $ = function (id) { return document.getElementById(id); };

  // ---------- helpers ----------
  function esc(s) {
    return String(s == null ? "" : s).replace(/[&<>"']/g, function (c) {
      return { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c];
    });
  }
  // Sample data cites placeholder hosts; never render those as live links.
  function isPlaceholder(u) {
    try { return /(^|\.)example\.(com|org|net)$/i.test(new URL(String(u)).hostname); } catch (e) { return false; }
  }
  function safeUrl(u) {
    try {
      var url = new URL(String(u));
      if (isPlaceholder(url.href)) return null;
      return url.protocol === "https:" || url.protocol === "http:" ? url.href : null;
    } catch (e) { return null; }
  }
  function host(u) {
    try { return new URL(u).hostname.replace(/^www\./, ""); } catch (e) { return String(u); }
  }
  function plural(n, word) {
    return n + " " + word + (n === 1 ? "" : /(s|ch|sh|x)$/.test(word) ? "es" : "s");
  }
  function fmtDate(d) {
    if (!d) return "";
    var parts = String(d).slice(0, 10).split("-");
    if (parts.length !== 3) return String(d);
    var dt = new Date(Date.UTC(+parts[0], +parts[1] - 1, +parts[2]));
    return dt.toLocaleDateString(undefined, { year: "numeric", month: "short", day: "numeric", timeZone: "UTC" });
  }
  function getJSON(path) {
    return fetch(path, { cache: "no-cache" }).then(function (r) {
      if (!r.ok) throw new Error(path + " returned HTTP " + r.status);
      return r.json();
    });
  }
  function count(list, key, value) {
    return list.filter(function (x) { return x[key] === value; }).length;
  }

  // ---------- color theme ----------
  function currentScheme() {
    var t = document.documentElement.getAttribute("data-theme");
    if (t === "light" || t === "dark") return t;
    return window.matchMedia && window.matchMedia("(prefers-color-scheme: dark)").matches ? "dark" : "light";
  }
  function setThemeLabel() {
    var t = document.documentElement.getAttribute("data-theme") || "auto";
    var b = $("theme-toggle");
    b.setAttribute("aria-label", "Color theme: " + t);
    b.title = "Color theme: " + t;
  }
  $("theme-toggle").addEventListener("click", function () {
    var order = ["auto", "light", "dark"];
    var cur = document.documentElement.getAttribute("data-theme") || "auto";
    var next = order[(order.indexOf(cur) + 1) % order.length];
    if (next === "auto") document.documentElement.removeAttribute("data-theme");
    else document.documentElement.setAttribute("data-theme", next);
    try { localStorage.setItem("tb-theme", next); } catch (e) {}
    setThemeLabel();
    if (state.view === "diagram") renderDiagram();
  });
  if (window.matchMedia) {
    var mq = window.matchMedia("(prefers-color-scheme: dark)");
    var onChange = function () { if (state.view === "diagram") renderDiagram(); };
    if (mq.addEventListener) mq.addEventListener("change", onChange);
  }
  setThemeLabel();

  // ---------- load ----------
  function showError(msg) {
    var el = $("load-error");
    el.innerHTML = msg;
    el.hidden = false;
  }

  getJSON("data/index.json")
    .then(function (index) {
      state.index = index;
      var themes = index.themes || [];
      if (!themes.length) {
        showError("No published theses yet. They appear after the first scheduled Claude run.");
        return;
      }
      renderTabs(themes);
      var wanted = decodeURIComponent((location.hash || "").slice(1));
      var pick = themes.filter(function (t) { return t.slug === wanted; })[0] || themes[0];
      selectTheme(pick.slug);
    })
    .catch(function (err) {
      showError(
        "Could not load <code>data/index.json</code> (" + esc(err.message) + "). " +
        "If you opened this file directly, serve the folder instead: " +
        "<code>python3 -m http.server -d docs 8080</code>"
      );
    });

  window.addEventListener("hashchange", function () {
    var slug = decodeURIComponent(location.hash.slice(1));
    if (slug && (!state.current || state.current.slug !== slug)) selectTheme(slug);
  });

  function renderTabs(themes) {
    var root = $("theme-tabs");
    root.innerHTML = themes.map(function (t) {
      return '<button type="button" role="tab" class="theme-tab" data-slug="' + esc(t.slug) +
        '" aria-selected="false">' + esc(t.theme) + "</button>";
    }).join("");
    root.querySelectorAll(".theme-tab").forEach(function (b) {
      b.addEventListener("click", function () { selectTheme(b.dataset.slug); });
    });
  }

  function selectTheme(slug) {
    var entry = (state.index.themes || []).filter(function (t) { return t.slug === slug; })[0];
    if (!entry) return;
    document.querySelectorAll(".theme-tab").forEach(function (b) {
      b.setAttribute("aria-selected", b.dataset.slug === slug ? "true" : "false");
    });
    if (location.hash.slice(1) !== slug) history.replaceState(null, "", "#" + slug);
    var p = state.cache[slug] ? Promise.resolve(state.cache[slug]) : getJSON("data/" + entry.file);
    p.then(function (data) {
      state.cache[slug] = data;
      state.current = data;
      $("load-error").hidden = true;
      render(data);
    }).catch(function (err) {
      showError("Could not load the thesis for " + esc(entry.theme) + " (" + esc(err.message) + ").");
    });
  }

  // ---------- render ----------
  function render(d) {
    var t = d.thesis || {};
    var nodes = t.nodes || [];
    var crit = d.critiques || [];
    var research = d.research || {};

    $("sample-banner").hidden = !d.sample;
    document.title = d.theme + " | Thesis Builder";

    // Run metadata
    var meta = [
      ["Run date", fmtDate(d.run_date)],
      ["Nodes", nodes.length],
      ["Sources", research.unique_urls != null ? research.unique_urls : "n/a"],
      ["Critiques", crit.length],
    ];
    if (d.eval && d.eval.total != null) meta.push(["Eval", d.eval.total + "/20"]);
    $("run-meta").innerHTML = meta.map(function (m) {
      return "<div><dt>" + esc(m[0]) + "</dt><dd>" + esc(m[1]) + "</dd></div>";
    }).join("");

    // Pipeline stats
    $("generated-by").textContent = (GEN_LABEL[d.generated_by] || d.generated_by || "") +
      (d.sample ? " (sample)" : "");
    $("p-theme").textContent = d.theme;
    $("p-research").textContent = plural(research.queries_run || 0, "search") + ", " +
      (research.summaries || 0) + " source summaries";
    $("p-skeptic").textContent = plural(crit.length, "critique") + ": " +
      count(crit, "verdict", "weak") + " weak, " + count(crit, "verdict", "mixed") + " mixed, " +
      count(crit, "verdict", "strong") + " strong";
    $("p-synth").textContent = plural(nodes.length, "node") + ", " +
      count(crit, "stance", "conceded") + " concessions, " + plural((t.investable_picks || []).length, "pick");
    var ev = d.eval || {};
    var hc = ev.hard_checks;
    $("p-eval").textContent = (hc ? (hc.passed ? "Golden checks pass" : plural(hc.failures.length, "golden check") + " failing") : "No golden spec") +
      (ev.total != null ? ", judge " + ev.total + "/20" : "");

    // Summary, headlines, picks
    $("summary").textContent = t.summary || "";
    var heads = d.headline_concerns && d.headline_concerns.length ? d.headline_concerns : (t.skeptic_notes || []);
    $("headlines").innerHTML = heads.map(function (h) { return "<li>" + esc(h) + "</li>"; }).join("");
    $("picks").innerHTML = (t.investable_picks || []).map(function (p) {
      var m = String(p).match(/^\s*([^:\u2014]+?)\s*(?::|\u2014|\s-\s)\s*([\s\S]*)$/);
      var ticker = m ? m[1] : p;
      var why = m ? m[2] : "";
      return '<li><span class="pick-ticker">' + esc(ticker) + '</span><span class="pick-why">' + esc(why) + "</span></li>";
    }).join("");

    renderTree(nodes, crit);
    renderDebateFilters(nodes);
    renderDebate();
    renderEval(d.eval);
    renderMemo(d.memo_md);
    if (state.view === "diagram") renderDiagram();
  }

  function renderTree(nodes, crit) {
    var byNode = {};
    crit.forEach(function (c) { (byNode[c.node_name] = byNode[c.node_name] || []).push(c); });
    $("view-tree").innerHTML = LAYERS.map(function (l, i) {
      var list = nodes.filter(function (n) { return n.layer === l[0]; });
      return '<section class="layer" data-layer="' + l[0] + '">' +
        '<div class="layer-head"><span class="layer-step">' + (i + 1) + "</span><h3>" + esc(l[1]) +
        '</h3><span class="count">' + list.length + "</span></div>" +
        (list.length ? list.map(function (n) { return nodeCard(n, byNode[n.name] || []); }).join("") :
          '<div class="empty">No nodes in this layer.</div>') +
        "</section>";
    }).join("");
    $("view-tree").querySelectorAll("[data-jump]").forEach(function (b) {
      b.addEventListener("click", function () {
        $("f-node").value = b.dataset.jump;
        $("f-angle").value = "";
        $("f-stance").value = "";
        renderDebate();
        $("h-debate").scrollIntoView({ behavior: "smooth", block: "start" });
      });
    });
  }

  function nodeCard(n, crit) {
    var conf = Math.max(0, Math.min(1, Number(n.confidence) || 0));
    var chips = (n.public_names || []).map(function (x) { return '<span class="chip ticker">' + esc(x) + "</span>"; })
      .concat((n.private_names || []).map(function (x) { return '<span class="chip private" title="Private company">' + esc(x) + "</span>"; }))
      .join("");
    var facts = (n.catalysts || []).map(function (x) { return '<li class="cat" title="Catalyst">' + esc(x) + "</li>"; })
      .concat((n.risks || []).map(function (x) { return '<li class="risk" title="Risk">' + esc(x) + "</li>"; }))
      .join("");
    var sources = (n.sources || []).map(function (u) {
      var s = safeUrl(u);
      if (!s && isPlaceholder(u)) return '<span class="muted">sample source</span>';
      return s ? '<a href="' + esc(s) + '" rel="noopener nofollow" target="_blank">' + esc(host(s)) + "</a>" : "";
    }).filter(Boolean).join(", ");
    var verdicts = crit.map(function (c) {
      return '<span class="badge ' + esc(c.verdict) + '" title="' + esc(ANGLE_LABEL[c.angle] || c.angle) + '">' + esc(c.verdict) + "</span>";
    }).join("");
    return '<article class="node">' +
      "<h4>" + esc(n.name) + "</h4>" +
      '<div class="conf" title="Confidence after the skeptic pass"><span>Confidence</span>' +
      '<span class="conf-bar"><span style="width:' + Math.round(conf * 100) + '%"></span></span><span>' + conf.toFixed(2) + "</span></div>" +
      "<p>" + esc(n.description) + "</p>" +
      (chips ? '<div class="chips">' + chips + "</div>" : "") +
      (facts ? '<ul class="facts">' + facts + "</ul>" : "") +
      '<div class="node-foot"><span>' + (sources ? "Sources: " + sources : "") + "</span>" +
      (crit.length ? '<span class="verdicts">' + verdicts + "</span>" +
        '<button type="button" class="link-btn" data-jump="' + esc(n.name) + '">See critiques</button>' : "") +
      "</div></article>";
  }

  function renderDebateFilters(nodes) {
    var sel = $("f-node");
    sel.innerHTML = '<option value="">All nodes</option>' + nodes.map(function (n) {
      return '<option value="' + esc(n.name) + '">' + esc(n.name) + "</option>";
    }).join("");
    $("f-angle").value = "";
    $("f-stance").value = "";
  }
  ["f-node", "f-angle", "f-stance"].forEach(function (id) { $(id).addEventListener("change", renderDebate); });

  function renderDebate() {
    var d = state.current;
    if (!d) return;
    var fNode = $("f-node").value, fAngle = $("f-angle").value, fStance = $("f-stance").value;
    var all = d.critiques || [];
    var crit = all.filter(function (c) {
      return (!fNode || c.node_name === fNode) && (!fAngle || c.angle === fAngle) && (!fStance || c.stance === fStance);
    });
    $("debate-tally").textContent = "Showing " + crit.length + " of " + plural(all.length, "critique") +
      ". Left: the Skeptic's attack. Right: how the Synthesizer answered it.";
    if (!crit.length) {
      $("debate").innerHTML = '<div class="empty">No critiques match these filters.</div>';
      return;
    }
    var nodes = (d.thesis && d.thesis.nodes) || [];
    var order = {};
    nodes.forEach(function (n, i) {
      order[n.name] = LAYERS.map(function (l) { return l[0]; }).indexOf(n.layer) * 1000 + i;
    });
    var layerOf = {};
    nodes.forEach(function (n) { layerOf[n.name] = n.layer; });
    var angleOrder = Object.keys(ANGLE_LABEL);
    var groups = {};
    crit.forEach(function (c) { (groups[c.node_name] = groups[c.node_name] || []).push(c); });
    var names = Object.keys(groups).sort(function (a, b) { return (order[a] || 0) - (order[b] || 0); });
    $("debate").innerHTML = names.map(function (name) {
      var items = groups[name].slice().sort(function (a, b) { return angleOrder.indexOf(a.angle) - angleOrder.indexOf(b.angle); });
      return '<div class="debate-group"><h3>' + esc(name) +
        '<span class="layer-tag">' + esc(LAYER_LABEL[layerOf[name]] || "") + "</span></h3>" +
        items.map(exchange).join("") + "</div>";
    }).join("");
  }

  function exchange(c) {
    return '<div class="exchange">' +
      '<div class="side critic"><div class="side-head"><strong>Skeptic</strong>' +
      '<span class="badge angle">' + esc(ANGLE_LABEL[c.angle] || c.angle) + "</span>" +
      '<span class="badge ' + esc(c.verdict) + '">' + esc(c.verdict) + "</span></div>" +
      "<p>" + esc(c.argument) + "</p>" +
      (c.suggested_change ? '<p class="suggest">Suggested change: ' + esc(c.suggested_change) + "</p>" : "") +
      "</div>" +
      '<div class="side answer"><div class="side-head"><strong>Synthesizer</strong>' +
      '<span class="badge ' + esc(c.stance) + '">' + esc(STANCE_LABEL[c.stance] || c.stance) + "</span></div>" +
      "<p>" + esc(c.rebuttal) + "</p></div></div>";
  }

  function renderEval(ev) {
    var root = $("eval");
    $("eval-judge").textContent = ev && ev.judge ? "Judge: " + ev.judge + (ev.scored_at ? ", " + fmtDate(ev.scored_at) : "") : "";
    if (!ev || (!ev.scores && !ev.hard_checks)) {
      root.innerHTML = '<div class="empty">Not scored yet.</div>';
      return;
    }
    var scores = "";
    if (ev.scores) {
      scores = '<div><div class="total">' + esc(ev.total != null ? ev.total : "") + "<small> / 20</small></div>" +
        '<p class="muted small">LLM-judge rubric from evals/judges.py. Each dimension 0 to 5; the rubric treats 2 as the default for a generic thesis.</p>' +
        '<div class="scores">' + DIMENSIONS.map(function (k) {
          var s = ev.scores[k] || { score: 0, justification: "" };
          return '<div class="score-row"><span class="name">' + esc(k) + '</span><span class="bar"><span style="width:' +
            (Number(s.score) / 5) * 100 + '%"></span></span><span class="val">' + esc(s.score) + "/5</span>" +
            '<span class="why">' + esc(s.justification) + "</span></div>";
        }).join("") + "</div></div>";
    } else {
      scores = '<div class="empty">No rubric score for this run.</div>';
    }
    var hc = ev.hard_checks;
    var checks = '<div class="checks"><h3>Golden-spec hard checks</h3>' +
      (hc ? (hc.passed ? '<p class="pass">All requirements met</p>' :
        '<p class="fail">' + plural(hc.failures.length, "requirement") + " not met</p><ul>" +
        hc.failures.map(function (f) { return "<li>" + esc(f) + "</li>"; }).join("") + "</ul>") +
        (hc.golden ? '<p class="muted small">Spec: ' + esc(hc.golden) + ". Checked by scripts/validate_thesis.py with no LLM.</p>" : "")
        : '<p class="muted">No golden spec for this theme.</p>') + "</div>";
    root.innerHTML = scores + checks;
  }

  function renderMemo(md) {
    var el = $("memo");
    if (!md) { el.innerHTML = '<div class="empty">No memo.</div>'; return; }
    if (window.marked && typeof window.marked.parse === "function") {
      // Escape raw HTML before markdown parsing, then keep only http(s) links.
      el.innerHTML = window.marked.parse(String(md).replace(/&/g, "&amp;").replace(/</g, "&lt;"));
      el.querySelectorAll("a").forEach(function (a) {
        var s = safeUrl(a.getAttribute("href"));
        if (s) { a.href = s; a.rel = "noopener nofollow"; a.target = "_blank"; }
        else a.removeAttribute("href");
      });
    } else {
      el.innerHTML = "<pre>" + esc(md) + "</pre>";
    }
  }

  // ---------- value chain view toggle + Mermaid ----------
  document.querySelectorAll(".seg-btn").forEach(function (b) {
    b.addEventListener("click", function () {
      state.view = b.dataset.view;
      document.querySelectorAll(".seg-btn").forEach(function (x) {
        var on = x === b;
        x.classList.toggle("active", on);
        x.setAttribute("aria-selected", on ? "true" : "false");
      });
      $("view-tree").hidden = state.view !== "tree";
      $("view-diagram").hidden = state.view !== "diagram";
      if (state.view === "diagram") renderDiagram();
    });
  });

  var diagramSeq = 0;
  function renderDiagram() {
    var out = $("diagram-out");
    var d = state.current;
    if (!d || !d.diagram_mmd) { out.innerHTML = '<div class="empty">No diagram.</div>'; return; }
    if (!window.mermaid) {
      out.innerHTML = "<pre>" + esc(d.diagram_mmd) + "</pre>";
      return;
    }
    window.mermaid.initialize({
      startOnLoad: false,
      securityLevel: "strict",
      theme: currentScheme() === "dark" ? "dark" : "default",
      flowchart: { htmlLabels: true, curve: "basis" },
    });
    diagramSeq += 1;
    window.mermaid.render("vc-diagram-" + diagramSeq, d.diagram_mmd)
      .then(function (res) { out.innerHTML = res.svg; })
      .catch(function () { out.innerHTML = "<pre>" + esc(d.diagram_mmd) + "</pre>"; });
  }
})();
